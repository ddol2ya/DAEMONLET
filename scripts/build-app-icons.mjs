import { execFile } from 'node:child_process'
import { promisify } from 'node:util'
import { mkdir, mkdtemp, readFile, rm, writeFile } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { join, resolve } from 'node:path'
import { createHash } from 'node:crypto'

// Format/size exports of the selected A2/M2 originals. No image redesign.
if (process.platform !== 'darwin') throw Error('macOS sips and iconutil are required to regenerate these assets')
const run = promisify(execFile), root = resolve(import.meta.dirname, '..')
const assets = join(root, 'electron/assets'), source = join(assets, 'icon-source')
const temporary = await mkdtemp(join(tmpdir(), 'daemonlet-icons-'))
try {
  const iconset = join(temporary, 'appIcon.iconset')
  await mkdir(iconset)
  for (const size of [16, 32, 128, 256, 512]) for (const scale of [1, 2]) {
    await run('/usr/bin/sips', ['-z', String(size * scale), String(size * scale), join(source, 'app-a2-rabbit.png'), '--out', join(iconset, `icon_${size}x${size}${scale === 2 ? '@2x' : ''}.png`)])
  }
  await run('/usr/bin/iconutil', ['-c', 'icns', iconset, '-o', join(assets, 'appIcon.icns')])
  const tray = []
  for (const scale of [1, 2]) {
    const path = join(assets, `trayTemplate${scale === 2 ? '@2x' : ''}.png`)
    await run('/usr/bin/sips', ['-z', String(18 * scale), String(18 * scale), join(source, 'menu-m2-rabbit.png'), '--out', path])
    tray.push((await readFile(path)).toString('base64'))
  }
  await writeFile(join(root, 'electron/main/TrayIconData.ts'), `// Generated by scripts/build-app-icons.mjs from the selected M2 source.\nexport const TRAY_TEMPLATE_PNG = ${JSON.stringify(tray[0])}\nexport const TRAY_TEMPLATE_PNG_2X = ${JSON.stringify(tray[1])}\n`)
  const sha256 = async file => createHash('sha256').update(await readFile(join(assets, file))).digest('hex')
  const files = ['icon-source/app-a2-rabbit.png', 'icon-source/menu-m2-rabbit.png', 'appIcon.icns', 'trayTemplate.png', 'trayTemplate@2x.png']
  const hashes = Object.fromEntries(await Promise.all(files.map(async file => [file, await sha256(file)])))
  await writeFile(join(assets, 'icon-source/manifest.json'), JSON.stringify({ selection: { app: 'A2', menu: 'M2' }, generator: 'built-in image_gen', export: 'sips + iconutil', trayLogicalSize: 18, trayScaleFactors: [1, 2], sha256: hashes }, null, 2) + '\n')
  console.log('Exported A2 app icon and M2 18px/36px template icons')
} finally { await rm(temporary, { recursive: true, force: true }) }
